(function(){
  // Active link
  var page = window.location.pathname.split('/').pop() || 'index';
  document.querySelectorAll('.wh-a').forEach(function(a){
    if(a.getAttribute('href') === page) a.classList.add('active');
  });

  // User dropdown
  window.whToggle = function(){
    var dm  = document.getElementById('wh-dm');
    var chv = document.getElementById('wh-chv');
    if(!dm) return;
    var open = dm.classList.toggle('open');
    if(chv) chv.style.transform = open ? 'rotate(180deg)' : '';
  };
  document.addEventListener('click', function(e){
    var trig = document.getElementById('wh-utrig');
    var dm   = document.getElementById('wh-dm');
    if(!dm || !trig) return;
    if(!trig.contains(e.target) && !dm.contains(e.target)){
      dm.classList.remove('open');
      var chv = document.getElementById('wh-chv');
      if(chv) chv.style.transform = '';
    }
  });

  // Mobile drawer
  window.whDrawer = function(){
    var d    = document.getElementById('wh-drawer');
    var icon = document.getElementById('wh-ham-icon');
    if(!d) return;
    var open = d.classList.toggle('open');
    if(icon) icon.className = open ? 'fas fa-times' : 'fas fa-bars';
  };

  // Live search
  var inp  = document.getElementById('wh-q');
  var drop = document.getElementById('wh-drop');
  var tmr, hlIdx = -1;
  if(inp && drop){
    inp.addEventListener('input', function(){
      clearTimeout(tmr);
      var q = this.value.trim();
      if(q.length < 2){ drop.style.display='none'; return; }
      tmr = setTimeout(function(){ loadSug(q); }, 280);
    });
    inp.addEventListener('keydown', function(e){
      var rows = drop.querySelectorAll('.wh-sug');
      if(!rows.length) return;
      if(e.key==='ArrowDown'){ e.preventDefault(); hlIdx=Math.min(hlIdx+1,rows.length-1); hl(rows); }
      else if(e.key==='ArrowUp'){ e.preventDefault(); hlIdx=Math.max(hlIdx-1,-1); hl(rows); }
      else if(e.key==='Enter' && hlIdx>=0){ e.preventDefault(); window.location.href=rows[hlIdx].href; }
      else if(e.key==='Escape'){ drop.style.display='none'; }
    });
    document.addEventListener('click', function(e){
      if(!inp.contains(e.target) && !drop.contains(e.target)) drop.style.display='none';
    });
  }
  function hl(rows){
    rows.forEach(function(r,i){
      r.style.background = i===hlIdx ? 'rgba(255,107,53,.12)' : '';
      if(i===hlIdx) r.scrollIntoView({block:'nearest'});
    });
  }
  function loadSug(q){
    drop.innerHTML = '<div class="wh-msg"><i class="fas fa-spinner wh-spin"></i> Searching\u2026</div>';
    drop.style.display = 'block';
    fetch('search_ajax.php?q='+encodeURIComponent(q))
      .then(function(r){ return r.text(); })
      .then(function(html){
        var d = document.createElement('div'); d.textContent = q;
        drop.innerHTML = html.trim()
          ? html
          : '<div class="wh-msg">No results for \u201c'+d.innerHTML+'\u201d</div>';
        drop.style.display = 'block';
        hlIdx = -1;
      })
      .catch(function(){ drop.innerHTML='<div class="wh-msg">Could not load results</div>'; });
  }
})();

