function checkNewMessages() {
    fetch('check_notifications')
        .then(response => response.json())
        .then(data => {
            // Update admin bell badge
            if (data.admin_unread > 0) {
                const bellBadge = document.querySelector('.msg-bell-btn .badge-count');
                if (bellBadge) {
                    bellBadge.textContent = data.admin_unread;
                    bellBadge.style.display = 'block';
                } else {
                    const bellBtn = document.querySelector('.msg-bell-btn');
                    if (bellBtn && !bellBtn.querySelector('.badge-count')) {
                        const newBadge = document.createElement('span');
                        newBadge.className = 'badge-count';
                        newBadge.textContent = data.admin_unread;
                        bellBtn.appendChild(newBadge);
                    }
                }
            } else {
                const bellBadge = document.querySelector('.msg-bell-btn .badge-count');
                if (bellBadge) {
                    bellBadge.style.display = 'none';
                }
            }
            
            // Update user avatar badge
            if (data.user_unread > 0) {
                const userBadge = document.querySelector('.user-msg-badge');
                if (userBadge) {
                    userBadge.textContent = data.user_unread;
                    userBadge.style.display = 'flex';
                } else {
                    const userAvatar = document.querySelector('.wh-av');
                    if (userAvatar && !userAvatar.querySelector('.user-msg-badge')) {
                        const newBadge = document.createElement('span');
                        newBadge.className = 'user-msg-badge';
                        newBadge.textContent = data.user_unread;
                        userAvatar.style.position = 'relative';
                        userAvatar.appendChild(newBadge);
                    }
                }
                
                const dropdownBadge = document.querySelector('.wh-di[href="my_messages"] .msg-badge-dropdown');
                if (dropdownBadge) {
                    dropdownBadge.textContent = data.user_unread + ' new';
                }
            } else {
                const userBadge = document.querySelector('.user-msg-badge');
                if (userBadge) {
                    userBadge.style.display = 'none';
                }
                const dropdownBadge = document.querySelector('.wh-di[href="my_messages"] .msg-badge-dropdown');
                if (dropdownBadge) {
                    dropdownBadge.remove();
                }
            }
        })
        .catch(err => console.log('Notification check error:', err));
}

// Check for new messages every 30 seconds
setInterval(checkNewMessages, 30000);

// Also check immediately when page loads
document.addEventListener('DOMContentLoaded', function() {
    checkNewMessages();
});
